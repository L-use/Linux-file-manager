export let language = localStorage.getItem('fm-language') === 'en' ? 'en' : 'zh';
export function t(key, values = {}) {
  return (strings[key]?.[language === 'en' ? 1 : 0] || strings.io[language === 'en' ? 1 : 0])
    .replace(/\{(\w+)\}/g, (_, field) => values[field] ?? '');
}
export function setLanguage(next) {
  language = next;
  localStorage.setItem('fm-language', next);
  translate(document);
}
export function translate(scope) {
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.title = t('title');
  for (const node of scope.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of scope.querySelectorAll('[data-label]')) {
    node.title = t(node.dataset.label);
    node.setAttribute('aria-label', node.title);
  }
  for (const node of scope.querySelectorAll('[data-placeholder]')) node.placeholder = t(node.dataset.placeholder);
}
